export function slugifyRoleTitle(title: string): string {
  return (
    'custom-' +
    title
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/(^-|-$)/g, '')
      .slice(0, 40)
  );
}
